/** May this permission ship in a production build? Only recorded approval or demo provenance. */
export function isPublishable(permission: PublicationPermission): boolean {
  switch (permission.status) {
    case 'approved': return Boolean(permission.evidence.trim() && permission.reviewedAt.trim());
    case 'demo': return Boolean(permission.provenance.trim() && permission.license.trim());
    default: return false;
  }
}

/** Builds show only publishable media; `astro dev` may also preview media under review. */
export function canShow(permission: PublicationPermission, localPreview: boolean): boolean {
  return isPublishable(permission) || (localPreview && permission.status === 'local-preview');
}

export function canUseVideo(video: VideoRecord, localPreview: boolean): boolean {
  return canShow(video.permission, localPreview);
}

export function canUseMedia(media: MediaRecord, localPreview: boolean): boolean {
  if (media.kind === 'promotion' || media.category === 'promocional') return false;
  return canShow(media.permission, localPreview);
}

export function isWork(media: MediaRecord): media is MediaRecord & { category: WorkCategory } {
  return Object.hasOwn(workCategories, media.category) && (media.kind === 'result' || media.kind === 'process');
}

/** True when the given media are illustrative stand-ins: the site then says so. */
export const showsDemoMedia = (items: readonly { readonly permission: PublicationPermission }[]): boolean =>
  items.some((item) => item.permission.status === 'demo');
