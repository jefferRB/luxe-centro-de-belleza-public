/** The managed-photo manifest: what the LUXE admin changed on top of the curated catalog.
 * It lives outside the repository and the published folder (LUXE_MEDIA_DIR), so code
 * updates, rebuilds and restarts never lose it. An empty manifest reproduces the site
 * exactly as the catalog describes it. Pure module: shared by the build, the admin
 * server and the tests. */
import { workCategories, type WorkCategory } from '../data/media-catalog.ts';

export const MANIFEST_VERSION = 1;
/** Photo ids handled by the admin that are not in the media catalog. */
export const HERO_ID = 'recepcion';
export const FACADE_ID = 'fachada';

export type ManagedSection = 'portada' | 'trabajos' | 'espacio' | 'fachada';

export interface UploadRef {
  /** `<uuid>.webp` inside LUXE_MEDIA_DIR/uploads: generated by the server, never user-named. */
  readonly file: string;
  readonly width: number;
  readonly height: number;
}

/** Change applied to any photo (catalog or uploaded) by its stable id. */
export interface PhotoEdit {
  readonly alt?: string;
  readonly title?: string;
  readonly replacement?: UploadRef;
  /** Retired from the site; files and data are kept so it can be restored. */
  readonly removed?: boolean;
}

interface AddedBase {
  readonly id: string;
  readonly image: UploadRef;
  readonly alt: string;
  /** Short visible name: the work's title or the space stop's title. */
  readonly title: string;
  readonly createdAt: string;
}
export interface AddedWork extends AddedBase { readonly section: 'trabajos'; readonly category: WorkCategory }
export interface AddedSpace extends AddedBase { readonly section: 'espacio'; readonly area: string }
export type AddedPhoto = AddedWork | AddedSpace;

export interface MediaManifest {
  readonly version: typeof MANIFEST_VERSION;
  /** Increments on every save: the admin sends it back to detect concurrent edits. */
  readonly revision: number;
  readonly updatedAt: string | null;
  readonly edits: Readonly<Record<string, PhotoEdit>>;
  readonly added: readonly AddedPhoto[];
  /** Explicit display order; ids not listed keep their catalog order after the listed ones. */
  readonly order: { readonly trabajos?: readonly string[]; readonly espacio?: readonly string[] };
  /** Mundo LUXE: photos per specialty id, in order (the first sits on the equator). */
  readonly globe: Readonly<Record<string, readonly string[]>>;
}

export const LIMITS = {
  alt: { min: 8, max: 300 },
  title: { min: 2, max: 80 },
  area: { min: 2, max: 40 },
  globePerSpecialty: 4,
  spaceStops: { min: 2, max: 8 },
  works: { min: 1, max: 60 },
} as const;

export class ManifestError extends Error {}

export const emptyManifest = (): MediaManifest => ({ version: MANIFEST_VERSION, revision: 0, updatedAt: null, edits: {}, added: [], order: {}, globe: {} });

const ID = /^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$/;
const UPLOAD_FILE = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.webp$/;
// Control characters and angle brackets never belong in alt text or titles.
const UNSAFE_TEXT = /[\u0000-\u001f\u007f<>]/;

export const isPhotoId = (value: unknown): value is string => typeof value === 'string' && ID.test(value);
export const isUploadFile = (value: unknown): value is string => typeof value === 'string' && UPLOAD_FILE.test(value);
export const isWorkCategory = (value: unknown): value is WorkCategory => typeof value === 'string' && Object.hasOwn(workCategories, value);

const fail = (message: string): never => { throw new ManifestError(message); };
const record = (value: unknown, where: string): Record<string, unknown> =>
  value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : fail(`${where}: se esperaba un objeto`);

/** Normalises and validates a user-provided text; throws a readable message. */
export function cleanText(value: unknown, field: keyof typeof LIMITS & ('alt' | 'title' | 'area'), label: string): string {
  if (typeof value !== 'string') return fail(`${label}: falta el texto`);
  const text = value.normalize('NFC').replace(/\s+/g, ' ').trim();
  const { min, max } = LIMITS[field];
  if (text.length < min) return fail(`${label}: escribí al menos ${min} caracteres`);
  if (text.length > max) return fail(`${label}: máximo ${max} caracteres`);
  if (UNSAFE_TEXT.test(text)) return fail(`${label}: contiene caracteres no permitidos`);
  return text;
}

function uploadRef(value: unknown, where: string): UploadRef {
  const ref = record(value, where);
  if (!isUploadFile(ref.file)) fail(`${where}: archivo inválido`);
  const { width, height } = ref;
  if (!Number.isInteger(width) || !Number.isInteger(height) || (width as number) < 1 || (height as number) < 1 || (width as number) > 20000 || (height as number) > 20000) fail(`${where}: dimensiones inválidas`);
  return { file: ref.file as string, width: width as number, height: height as number };
}

function idList(value: unknown, where: string): string[] {
  if (!Array.isArray(value) || !value.every(isPhotoId)) return fail(`${where}: lista de ids inválida`);
  if (new Set(value).size !== value.length) fail(`${where}: ids repetidos`);
  return [...value];
}

const isoDate = (value: unknown, where: string): string => typeof value === 'string' && !Number.isNaN(Date.parse(value)) ? value : fail(`${where}: fecha inválida`);

/** Strict parse of a stored manifest: an unknown shape fails loudly instead of publishing a
 * half-understood site (the previous release stays online). */
export function parseManifest(raw: unknown): MediaManifest {
  const root = record(raw, 'manifest');
  if (root.version !== MANIFEST_VERSION) fail('manifest: versión no soportada');
  if (!Number.isInteger(root.revision) || (root.revision as number) < 0) fail('manifest: revisión inválida');
  const updatedAt = root.updatedAt === null ? null : isoDate(root.updatedAt, 'manifest.updatedAt');

  const edits: Record<string, PhotoEdit> = {};
  for (const [id, value] of Object.entries(record(root.edits, 'edits'))) {
    if (!isPhotoId(id)) fail(`edits: id inválido «${id}»`);
    const edit = record(value, `edits.${id}`);
    edits[id] = {
      ...(edit.alt !== undefined && { alt: cleanText(edit.alt, 'alt', `edits.${id}.alt`) }),
      ...(edit.title !== undefined && { title: cleanText(edit.title, 'title', `edits.${id}.title`) }),
      ...(edit.replacement !== undefined && { replacement: uploadRef(edit.replacement, `edits.${id}.replacement`) }),
      ...(edit.removed !== undefined && { removed: edit.removed === true ? true : fail(`edits.${id}.removed inválido`) }),
    };
  }

  if (!Array.isArray(root.added)) fail('added: se esperaba una lista');
  const added = (root.added as unknown[]).map((value, index): AddedPhoto => {
    const item = record(value, `added[${index}]`);
    if (!isPhotoId(item.id) || !(item.id as string).startsWith('subida-')) fail(`added[${index}]: id inválido`);
    const base = {
      id: item.id as string,
      image: uploadRef(item.image, `added[${index}].image`),
      alt: cleanText(item.alt, 'alt', `added[${index}].alt`),
      title: cleanText(item.title, 'title', `added[${index}].title`),
      createdAt: isoDate(item.createdAt, `added[${index}].createdAt`),
    };
    if (item.section === 'trabajos') return isWorkCategory(item.category) ? { ...base, section: 'trabajos', category: item.category } : fail(`added[${index}]: categoría inválida`);
    if (item.section === 'espacio') return { ...base, section: 'espacio', area: cleanText(item.area, 'area', `added[${index}].area`) };
    return fail(`added[${index}]: sección inválida`);
  });
  if (new Set(added.map((item) => item.id)).size !== added.length) fail('added: ids repetidos');

  const order = record(root.order, 'order');
  const globe: Record<string, string[]> = {};
  for (const [specialty, list] of Object.entries(record(root.globe, 'globe'))) {
    if (!isPhotoId(specialty)) fail(`globe: especialidad inválida «${specialty}»`);
    const ids = idList(list, `globe.${specialty}`);
    if (ids.length > LIMITS.globePerSpecialty) fail(`globe.${specialty}: máximo ${LIMITS.globePerSpecialty} fotografías`);
    globe[specialty] = ids;
  }
  return {
    version: MANIFEST_VERSION,
    revision: root.revision as number,
    updatedAt,
    edits,
    added,
    order: {
      ...(order.trabajos !== undefined && { trabajos: idList(order.trabajos, 'order.trabajos') }),
      ...(order.espacio !== undefined && { espacio: idList(order.espacio, 'order.espacio') }),
    },
    globe,
  };
}

/** The image a photo shows now: its replacement, else the upload it was created with. */
export function currentUpload(manifest: MediaManifest, id: string): UploadRef | undefined {
  return manifest.edits[id]?.replacement ?? manifest.added.find((item) => item.id === id)?.image;
}

/** Upload files shown by photos still on the site (the build imports exactly these). */
export function activeUploads(manifest: MediaManifest): UploadRef[] {
  const ids = new Set([...Object.keys(manifest.edits), ...manifest.added.map((item) => item.id)]);
  const refs = [...ids].filter((id) => !manifest.edits[id]?.removed).flatMap((id) => currentUpload(manifest, id) ?? []);
  return [...new Map(refs.map((ref) => [ref.file, ref])).values()];
}
