/** Media inventory and publication policy. No asset imports here (see data/media.assets.ts).
 *
 * Publication policy (docs/media-policy.md). A record's own permission is the only way into a
 * build; no list, flag or environment variable can widen it:
 *  - 'approved'      client media with recorded written authorization (evidence + date). Builds ship it.
 *  - 'demo'          redistributable demonstration media made for the public repository
 *                    (provenance + licence). Builds ship it, and the site says it is illustrative.
 *  - 'local-preview' client media still under review: only `astro dev` shows it, never a build.
 *  - 'pending' | 'third-party'  never shown.
 *
 * The public repository contains no client media: every record below is a demo illustration
 * generated by scripts/generate-demo-media.ts, standing in for the original photo with the same
 * id, category and aspect ratio, so the globe, the works gallery and the space tour behave as
 * they do on the production site. */
export type WorkCategory = 'cortes' | 'peluqueria' | 'unas' | 'cejas' | 'faciales';
export type MediaCategory = WorkCategory | 'espacio' | 'promocional';
export type PublicationPermission =
  | { readonly status: 'approved'; readonly evidence: string; readonly reviewedAt: string }
  | { readonly status: 'demo'; readonly provenance: string; readonly license: string }
  | { readonly status: 'local-preview' | 'pending' | 'third-party' };
export interface MediaRecord {
  readonly id: string;
  readonly source: string;
  readonly category: MediaCategory;
  readonly kind: 'result' | 'process' | 'interior' | 'exterior' | 'promotion';
  readonly alt: string;
  readonly caption: string;
  readonly order: number;
  readonly objectPosition?: `${number}% ${number}%`;
  /** Lighter variant of the same image for small surfaces (the globe); never shown alongside it. */
  readonly thumbSource?: string;
  readonly permission: PublicationPermission;
}

